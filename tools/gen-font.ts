// Reads Excalidraw's Excalifont and Virgil woff2 files (build/fonts, fetched
// by make fonts) and writes esketch-fonts.el: per font, units per em and,
// per character, the advance width and the glyph outline as SVG path data in
// font units with the baseline at y = 0, y pointing down.  Also writes the
// fonts' licence text to fonts/OFL.txt.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "fs";
// @ts-ignore
import wawoff2 from "wawoff2";
// @ts-ignore
import opentype from "opentype.js";

const dir = process.argv[2] ?? "build/fonts";
const families: Record<string, { id: number; upem: number; asc: number; desc: number;
  glyphs: Map<number, [number, string]>; kern: number; license: string; copyright: string }> = {};
for (const f of readdirSync(dir).filter(f => f.endsWith(".woff2")).sort()) {
  const ttf = await wawoff2.decompress(readFileSync(`${dir}/${f}`));
  const font = opentype.parse(ttf.buffer.slice(ttf.byteOffset, ttf.byteOffset + ttf.byteLength));
  const name = font.names.fontFamily.en;
  const fam = families[name] ??= { id: name === "Excalifont" ? 5 : 1, upem: font.unitsPerEm,
    asc: font.ascender, desc: font.descender, glyphs: new Map(), kern: 0,
    license: "", copyright: font.names.copyright?.en ?? "" };
  fam.kern += Object.keys(font.kerningPairs ?? {}).length;
  if (!fam.license && font.names.license?.en) fam.license = font.names.license.en;
  for (let i = 0; i < font.glyphs.length; i++) {
    const g = font.glyphs.get(i);
    for (const u of g.unicodes ?? []) {
      if (fam.glyphs.has(u)) continue;
      fam.glyphs.set(u, [g.advanceWidth, g.getPath(0, 0, font.unitsPerEm).toPathData(1)]);
    }
  }
}
const q = (s: string) => JSON.stringify(s);
let el = `;;; esketch-fonts.el --- Glyph outlines of Excalifont and Virgil  -*- lexical-binding: t; -*-

;; Generated by tools/gen-font.ts from Excalidraw's woff2 files; do not edit.
;; Excalifont and Virgil are licensed under the SIL Open Font License 1.1,
;; see fonts/OFL.txt.  Excalifont is a trademark of Excalidraw.

;;; Commentary:

;; Per font id: units per em, hhea ascender and descender, and a table from
;; character to (ADVANCE . PATH), PATH being SVG path data in font units with
;; the baseline at y = 0 and y pointing down.

;;; Code:

(defconst esketch-fonts
  (list
`;
for (const [name, f] of Object.entries(families)) {
  el += `   (list ${f.id} ${q(name)} ${f.upem} ${f.asc} ${f.desc}\n         #s(hash-table size ${f.glyphs.size} test eql data (\n`;
  for (const [u, [adv, d]] of [...f.glyphs].sort((a, b) => a[0] - b[0]))
    el += `   ${u} (${adv} . ${q(d)})\n`;
  el += `   )))\n`;
  console.log(`${name}: id ${f.id}, ${f.glyphs.size} glyphs, upem ${f.upem}, asc ${f.asc}, desc ${f.desc}, kerning pairs ${f.kern}`);
}
el += `  )
  "Fonts esketch draws text with: (ID NAME UPEM ASCENDER DESCENDER GLYPHS).")

(provide 'esketch-fonts)
;;; esketch-fonts.el ends here
`;
writeFileSync("esketch-fonts.el", el);
mkdirSync("fonts", { recursive: true });
const body = Object.values(families).map(f => f.license).find(l => l) ?? "";
writeFileSync("fonts/OFL.txt", Object.entries(families).map(([n, f]) => `${n}: ${f.copyright}`).join("\n") + "\n\n" + body + "\n");
